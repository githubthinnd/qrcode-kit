// Generates the JIS X 0208 data files from the Unicode Consortium mapping table kept in
// tests/fixtures/jis0208/JIS0208.TXT (unmodified; see THIRD_PARTY_NOTICES.md).
//   node scripts/generate-jis-x-0208.mjs
// Outputs:
//   src/core/jis-x-0208.ts          repertoire layout (18 runs of defined row/cell positions)
//   src/kanji-table/table.ts        the characters, in layout order (opt-in `qrcode-toolkit/kanji` entry)
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const root = join(import.meta.dirname, '..');
const source = readFileSync(join(root, 'tests/fixtures/jis0208/JIS0208.TXT'), 'utf8');

const entries = [];
for (const line of source.split('\n')) {
  const m = /^0x([0-9A-F]{4})\t0x([0-9A-F]{4})\t0x([0-9A-F]{4})/i.exec(line);
  if (!m) continue;
  const jis = parseInt(m[2], 16);
  const cell = ((jis >> 8) - 0x21) * 94 + ((jis & 0xff) - 0x21); // 0-based row/cell index
  entries.push({ cell, codePoint: parseInt(m[3], 16) });
}
entries.sort((a, b) => a.cell - b.cell);
if (entries.length !== 6879) throw new Error(`expected 6879 entries, found ${entries.length}`);
if (entries.some((e) => e.codePoint > 0xffff)) throw new Error('expected BMP-only characters');
if (new Set(entries.map((e) => e.codePoint)).size !== entries.length)
  throw new Error('duplicate code points');

const runs = [];
let start = entries[0].cell;
let previous = start;
for (const { cell } of entries.slice(1)) {
  if (cell === previous + 1) {
    previous = cell;
    continue;
  }
  runs.push([start, previous]);
  start = previous = cell;
}
runs.push([start, previous]);

const header = (what) => `// GENERATED by scripts/generate-jis-x-0208.mjs — do not edit.
// ${what}
// Source: "JIS X 0208 (1990) to Unicode", table version 2.0, © 2015 Unicode®, Inc.
// Terms of use: https://www.unicode.org/terms_of_use.html (see THIRD_PARTY_NOTICES.md).
`;

writeFileSync(
  join(root, 'src/core/jis-x-0208.ts'),
  `${header('Layout of the JIS X 0208 repertoire: inclusive [first, last] runs of defined cells, where a cell index is (row − 1) × 94 + (column − 1).')}
export const JIS_X_0208_RUNS: readonly (readonly [number, number])[] = ${JSON.stringify(runs)};

/** Number of characters in JIS X 0208. */
export const JIS_X_0208_SIZE = ${entries.length};

/**
 * Shift JIS codes (as in Kanji mode) whose Unicode counterpart differs between the
 * Unicode Consortium's JIS X 0208 table and Windows-31J (the WHATWG \`shift_jis\` decoder), and
 * which readers decode differently from each other. Kanji mode never uses them, so those
 * characters take the byte-mode path, which always round-trips.
 */
export const AMBIGUOUS_SHIFT_JIS_CODES: ReadonlySet<number> = new Set([0x815f, 0x8160, 0x8161, 0x817c, 0x8191, 0x8192, 0x81ca]);

/** Shift JIS code of the character at a JIS X 0208 cell index. */
export function shiftJisOfCell(cell: number): number {
  const j1 = Math.floor(cell / 94) + 0x21;
  const j2 = (cell % 94) + 0x21;
  const s1 = ((j1 - 0x21) >> 1) + (j1 <= 0x5e ? 0x81 : 0xc1);
  const s2 = j2 + (j1 & 1 ? (j2 < 0x60 ? 0x1f : 0x20) : 0x7e);
  return (s1 << 8) | s2;
}

/** Whether a Shift JIS code is a character of JIS X 0208 (ignoring the ambiguity exclusions). */
export function isJisX0208ShiftJis(code: number): boolean {
  const s1 = code >> 8;
  const s2 = code & 0xff;
  if (s2 < 0x40 || s2 === 0x7f || s2 > 0xfc) return false;
  const first = s1 >= 0xe0 ? s1 - 0xc1 : s1 - 0x81; // 0-based pair of rows
  if (first < 0 || (s1 > 0x9f && s1 < 0xe0)) return false;
  const odd = s2 < 0x9f;
  const column = odd ? s2 - (s2 < 0x7f ? 0x40 : 0x41) : s2 - 0x9f;
  const cell = (first * 2 + (odd ? 0 : 1)) * 94 + column;
  return JIS_X_0208_RUNS.some(([a, b]) => cell >= a && cell <= b);
}
`,
);

const chars = entries.map((e) => String.fromCharCode(e.codePoint)).join('');
writeFileSync(
  join(root, 'src/kanji-table/table.ts'),
  `${header('The characters of JIS X 0208 in layout order (see JIS_X_0208_RUNS in core/jis-x-0208.ts).')}
// prettier-ignore
export const JIS_X_0208_CHARACTERS = ${JSON.stringify(chars)};
`,
);
console.log(`generated ${entries.length} characters in ${runs.length} runs`);
